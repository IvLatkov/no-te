test('global search focuses, handles keyboard navigation, ignores editing shortcuts and opens each entity', async () => {
  const ui = await uiHarness('test-global-search-ui')
  const { click, input, waitFor, byLabel, byText, act, editor } = ui
  try {
    const project = { ...createProject({ name: 'Orbit project', description: 'Milestone launch' }), tasks: [{ ...createTask({ title: 'Orbit task' }), implementationNotes: 'Compile violet' }] }
    const rich = { type: 'doc', content: [{ type: 'paragraph', content: [{ type: 'text', text: 'Sapphire clue <img src=x onerror=alert(1)>', marks: [{ type: 'bold' }] }] }] }
    const note = createNote({ title: 'Orbit note', projectId: project.id, content: rich })
    localStorage.setItem(STORAGE_KEY, JSON.stringify([project]))
    localStorage.setItem(NOTES_STORAGE_KEY, JSON.stringify([note]))
    await ui.mount()
    const palette = () => document.querySelector('.global-search-modal')
    const key = async (element, value, options = {}) => { await act(async () => { element.dispatchEvent(new ui.dom.window.KeyboardEvent('keydown', { key: value, bubbles: true, cancelable: true, ...options })) }) }
    await key(document.body, 'k', { ctrlKey: true })
    assert.ok(palette())
    assert.equal(document.activeElement.getAttribute('aria-label'), 'Search everything')
    await input(palette().querySelector('input'), 'ORBIT')
    await waitFor(() => palette().querySelectorAll('[role="option"]').length === 3)
    assert.equal(palette().querySelectorAll('[role="group"]').length, 3)
    assert.match(palette().querySelector('mark').textContent.toLowerCase(), /orbit/)
    await key(palette().querySelector('input'), 'ArrowDown')
    assert.equal(palette().querySelectorAll('[role="option"]')[1].getAttribute('aria-selected'), 'true')
    await key(palette().querySelector('input'), 'ArrowUp')
    await key(palette().querySelector('input'), 'Enter')
    assert.equal(palette(), null)
    assert.equal(document.getElementById('project-title').textContent, project.name)
    await click(document.querySelector('[aria-label="Open global search"]'))
    await input(palette().querySelector('input'), 'COMPILE VIOLET')
    await waitFor(() => palette().querySelectorAll('[role="option"]').length === 1)
    await key(palette().querySelector('input'), 'Enter')
    assert.equal(document.getElementById('task-detail-title').value, 'Orbit task')
    await key(document.getElementById('task-detail-title'), 'k', { ctrlKey: true })
    assert.equal(palette(), null, 'shortcuts do not hijack task modal inputs')
    await click(byLabel('Search No-Te', document.querySelector('.task-details-modal')))
    assert.ok(palette(), 'an explicit search action is available inside task details')
    await key(palette().querySelector('input'), 'Escape')
    await click(byText('Done', document.querySelector('.task-details-modal')))
    await click(document.querySelector('[aria-label="Open global search"]'))
    await input(palette().querySelector('input'), 'SAPPHIRE')
    await waitFor(() => palette().querySelectorAll('[role="option"]').length === 1)
    assert.equal(palette().querySelector('img'), null, 'search excerpts render text without interpreting HTML')
    await key(palette().querySelector('input'), 'Enter')
    await waitFor(() => editor())
    assert.equal(document.querySelector('.note-title').value, note.title)
    assert.deepEqual(JSON.parse(localStorage.getItem(NOTES_STORAGE_KEY))[0].content, rich)
    await key(document.querySelector('.note-title'), 'k', { metaKey: true })
    assert.equal(palette(), null)
    await key(document.querySelector('.note-prose'), 'k', { ctrlKey: true })
    assert.equal(palette(), null, 'contenteditable retains its own keyboard shortcuts')
    await click(byLabel('Search No-Te', document.querySelector('.note-editor')))
    assert.ok(palette(), 'full-screen mobile editors have an explicit search action')
    await key(palette().querySelector('input'), 'Escape')
    await act(async () => { editor().commands.insertContent('Latest draft ') })
    const header = document.querySelector('[aria-label="Open global search"]')
    header.focus()
    await click(header)
    await key(palette().querySelector('input'), 'Escape')
    assert.equal(palette(), null)
    assert.ok(document.activeElement === header, 'focus returns to the search trigger')
    await key(document.body, 'k', { metaKey: true })
    await input(palette().querySelector('input'), 'milestone')
    await waitFor(() => palette().querySelectorAll('[role="option"]').length === 1)
    await click(palette().querySelector('[role="option"]'))
    assert.equal(document.getElementById('project-title').textContent, project.name)
    assert.match(JSON.stringify(JSON.parse(localStorage.getItem(NOTES_STORAGE_KEY))[0].content), /Latest draft/)
    assert.ok(byLabel('Open task Orbit task'))
  } finally { await ui.close() }
})

test('folder and tag UI preserves notes, applies combined filters, cleans references and retains filtered status dragging', async () => {
  const ui = await uiHarness('test-organization-ui')
  const { click, input, select, submit, byText, byLabel, waitFor, act, editor } = ui
  try {
    const a = { ...createProject({ name: 'Project A' }), tasks: [createTask({ title: 'Alpha task' }), createTask({ title: 'Zulu task' })] }
    const b = createProject({ name: 'Project B' })
    const bNote = createNote({ title: 'B note', projectId: b.id })
    localStorage.setItem(STORAGE_KEY, JSON.stringify([a, b]))
    localStorage.setItem(NOTES_STORAGE_KEY, JSON.stringify([bNote]))
    const org = () => JSON.parse(localStorage.getItem(ORGANIZATION_KEY))
    const notes = () => JSON.parse(localStorage.getItem(NOTES_STORAGE_KEY))
    const projects = () => JSON.parse(localStorage.getItem(STORAGE_KEY))
    const dialog = () => [...document.querySelectorAll('dialog')].at(-1)
    const foldersNav = () => document.querySelector('.folder-tree')
    await ui.mount()
    await openDocumentation({ click, waitFor })
    await waitFor(() => foldersNav())
    await click(byLabel('New folder'))
    await input(document.getElementById('folder-name'), 'A folder')
    await select(dialog().querySelector('.note-project-selector select'), a.id)
    await submit()
    const rootId = org().folders[0].id
    await click(byText('A folder', foldersNav()))
    await click(byText('Subfolder', foldersNav()))
    await input(document.getElementById('folder-name'), 'Child folder')
    await submit()
    const childId = org().folders[1].id
    await click(byText('Child folder', foldersNav()))
    await click(byText('Subfolder', foldersNav()))
    await input(document.getElementById('folder-name'), 'Leaf folder')
    await submit()
    const leafId = org().folders[2].id
    await click(byText('Leaf folder', foldersNav()))
    assert.equal(byText('Subfolder', foldersNav()).disabled, true)
    await click(byText('Rename', foldersNav()))
    await input(document.getElementById('folder-name'), 'Leaf renamed')
    await submit()
    assert.equal(org().folders.find(folder => folder.id === leafId).name, 'Leaf renamed')
    await click(byLabel('Collapse folder A folder'))
    assert.equal([...foldersNav().querySelectorAll('button')].some(button => button.textContent === 'Child folder'), false)
    await click(byLabel('Expand folder A folder'))
    await click(byText('Child folder', foldersNav()))
    await click(byText('New Note'))
    assert.equal(dialog().querySelector('[aria-label="Note folder"]').value, childId)
    await input(document.getElementById('new-note-title'), 'Organized note')
    await submit()
    await waitFor(() => editor())
    const organizedId = notes().find(note => note.title === 'Organized note').id
    assert.equal(notes().find(note => note.id === organizedId).projectId, a.id)
    await act(async () => { editor().commands.insertContent('Preserve this rich content') })
    await select(document.querySelector('.note-editor [aria-label="Note folder"]'), leafId)
    assert.equal(notes().find(note => note.id === organizedId).folderId, leafId)
    await select(document.querySelector('.note-editor .note-project-selector select'), b.id)
    assert.match(document.querySelector('.notes-error').textContent, /different project/)
    assert.equal(notes().find(note => note.id === organizedId).projectId, a.id)
    await click(byText('Dismiss'))

    await click(byLabel('New folder'))
    await input(document.getElementById('folder-name'), 'General folder')
    await submit()
    const generalId = org().folders.find(folder => folder.name === 'General folder').id
    await select(document.querySelector('.note-editor [aria-label="Note folder"]'), generalId)
    assert.equal(notes().find(note => note.id === organizedId).projectId, a.id, 'moving to a general folder does not change the project')
    await select(document.querySelector('.note-editor [aria-label="Note folder"]'), leafId)
    await click(byText('A folder', foldersNav()))
    await click(byText('Delete', foldersNav()))
    await click(byText('Cancel', dialog()))
    assert.equal(org().folders.length, 4)
    await click(byText('Delete', foldersNav()))
    await click(byText('Delete', dialog()))
    assert.equal(org().folders.length, 1)
    assert.equal(notes().find(note => note.id === organizedId).folderId, null)
    assert.equal(notes().find(note => note.id === organizedId).projectId, a.id)
    assert.match(JSON.stringify(notes().find(note => note.id === organizedId).content), /Preserve this rich content/)
    assert.equal(org().folders.some(folder => folder.id === rootId || folder.id === childId), false)
    await click([...document.querySelectorAll('.note-card')].find(card => card.textContent.includes('Organized note')))
    await waitFor(() => editor())
    const noteTags = () => document.querySelector('.note-editor .tag-selector')
    await click(noteTags().querySelector('summary'))
    await click(byText('Manage tags', noteTags()))
    for (const name of ['Focus', 'Later', 'Backend']) {
      await click(byText('New tag', dialog()))
      await input(document.getElementById('tag-name'), name)
      if (name === 'Later') await click(dialog().querySelector(`input[value="${TAG_COLORS[1].value}"]`))
      await submit()
    }
    const focusId = org().tags.find(tag => tag.name === 'Focus').id
    await click(byLabel('Edit tag Focus', dialog()))
    await input(document.getElementById('tag-name'), 'Priority')
    await submit()
    assert.equal(org().tags.find(tag => tag.name === 'Priority').id, focusId)
    await click(byLabel('Close dialog', dialog()))
    await click(byText('Priority', noteTags()))
    await click(byText('Later', noteTags()))
    assert.equal(notes().find(note => note.id === organizedId).tagIds.length, 2)
    await click(document.querySelector('.project-nav button'))
    await click(byLabel('Open task Alpha task'))
    const taskDetails = () => document.querySelector('.task-details-modal')
    const taskTags = () => taskDetails().querySelector('.tag-selector')
    await click(taskTags().querySelector('summary'))
    for (const name of ['Priority', 'Later', 'Backend']) await click(byText(name, taskTags()))
    assert.equal(projects()[0].tasks[0].tagIds.length, 3)
    await click(byText('Done', taskDetails()))
    const taggedCard = document.querySelector('.task-card')
    assert.equal(taggedCard.querySelectorAll('.tag-badge').length, 2)
    assert.equal(taggedCard.querySelector('.tag-extra').textContent, '+1')
    await click(byLabel('Open task Alpha task'))
    await click(taskTags().querySelector('summary'))
    await click(byText('Manage tags', taskTags()))
    await click(byLabel('Delete tag Priority', dialog()))
    await click(byText('Delete', dialog()))
    assert.equal(org().tags.some(tag => tag.id === focusId), false)
    assert.equal(projects()[0].tasks[0].tagIds.includes(focusId), false)
    assert.equal(notes().find(note => note.id === organizedId).tagIds.includes(focusId), false)
    await click(byLabel('Close dialog', dialog()))
    await input(document.getElementById('task-detail-description'), 'Editing after tag deletion')
    assert.equal(projects()[0].tasks[0].tagIds.includes(focusId), false, 'the open task draft cannot reintroduce a deleted tag')
    await click(byText('Done', taskDetails()))
    await input(document.querySelector('[aria-label="Search tasks"]'), 'ALPHA')
    await select(document.querySelector('[aria-label="Sort tasks"]'), 'title')
    const boardTags = document.querySelector('.board-filters .tag-selector')
    await click(boardTags.querySelector('summary'))
    await click(byText('Later', boardTags))
    assert.equal(document.querySelectorAll('.task-card').length, 1)
    const orderBefore = projects()[0].tasks.map(task => task.id)
    const payload = new Map()
    const transfer = { setData: (key, value) => payload.set(key, value), getData: key => payload.get(key) || '' }
    await act(async () => {
      const event = new ui.dom.window.Event('dragstart', { bubbles: true, cancelable: true })
      Object.defineProperty(event, 'dataTransfer', { value: transfer })
      document.querySelector('.task-card-open').dispatchEvent(event)
    })
    await act(async () => {
      for (const type of ['dragover', 'drop']) {
        const event = new ui.dom.window.Event(type, { bubbles: true, cancelable: true })
        Object.defineProperty(event, 'dataTransfer', { value: transfer })
        document.getElementById('column-done').closest('.board-column').dispatchEvent(event)
      }
    })
    assert.equal(projects()[0].tasks[0].status, 'done')
    assert.deepEqual(projects()[0].tasks.map(task => task.id), orderBefore)
    assert.ok(document.getElementById('column-done').closest('.board-column').querySelector('.task-card'))
    await openDocumentation({ click, waitFor })
    await waitFor(() => document.querySelector('.notes-panel'))
    await select(document.querySelector('[aria-label="Filter notes by project"]'), a.id)
    await click(byText('Unfiled', foldersNav()))
    const noteFilter = document.querySelector('.notes-panel .tag-selector')
    await click(noteFilter.querySelector('summary'))
    await click(byText('Later', noteFilter))
    assert.equal(document.querySelectorAll('.note-card').length, 1)
    assert.match(document.querySelector('.note-card').textContent, /Organized note/)
    await select(document.querySelector('[aria-label="Filter notes by project"]'), b.id)
    assert.equal(document.querySelectorAll('.note-card').length, 0)
    assert.match(document.querySelector('.notes-no-results').textContent, /No notes match/)
    await click(byText('Clear note filters'))
    await select(document.querySelector('[aria-label="Filter notes by project"]'), a.id)
    await click(byText('General folder', foldersNav()))
    await click(byText('Rename', foldersNav()))
    await input(document.getElementById('folder-name'), 'General renamed')
    await submit()
    assert.equal(org().folders.find(folder => folder.id === generalId).projectId, null, 'rename keeps a general folder general under a project filter')
    await ui.mount()
    await openDocumentation({ click, waitFor })
    await waitFor(() => foldersNav())
    assert.ok(byText('General renamed', foldersNav()))
    assert.equal(org().tags.length, 2)
    assert.equal(notes().find(note => note.id === organizedId).tagIds.length, 1)
    assert.equal(projects()[0].tasks[0].status, 'done')
  } finally { await ui.close() }
})

test('organization read errors preserve old data and quota failures keep forms and destructive operations retryable', async () => {
  const ui = await uiHarness('test-organization-errors-ui')
  const { click, input, submit, byText, byLabel, waitFor, editor } = ui
  try {
    const project = { ...createProject({ name: 'Preserved project' }), tasks: [{ ...createTask({ title: 'Preserved task' }), tagIds: ['tag'] }] }
    const note = createNote({ title: 'Preserved note', projectId: project.id, folderId: 'folder', tagIds: ['tag'] })
    const rawProjects = JSON.stringify([project])
    const rawNotes = JSON.stringify([note])
    localStorage.setItem(STORAGE_KEY, rawProjects)
    localStorage.setItem(NOTES_STORAGE_KEY, rawNotes)
    localStorage.setItem(ORGANIZATION_KEY, '{invalid')
    await ui.mount()
    assert.match(document.body.textContent, /Saved data has been preserved/)
    await openDocumentation({ click, waitFor })
    await waitFor(() => document.querySelector('.note-card'))
    assert.equal(byLabel('New folder').disabled, true)
    assert.equal(localStorage.getItem(ORGANIZATION_KEY), '{invalid')
    assert.equal(localStorage.getItem(STORAGE_KEY), rawProjects)
    assert.equal(localStorage.getItem(NOTES_STORAGE_KEY), rawNotes)
    const timestamp = new Date().toISOString()
    const data = { version: 1, folders: [{ id: 'folder', name: 'Preserved folder', projectId: project.id, parentFolderId: null, createdAt: timestamp, updatedAt: timestamp }], tags: [{ id: 'tag', name: 'Preserved tag', color: TAG_COLORS[0].value }] }
    localStorage.setItem(ORGANIZATION_KEY, JSON.stringify(data))
    await ui.mount()
    await openDocumentation({ click, waitFor })
    await waitFor(() => document.querySelector('.folder-tree'))
    const dialog = () => [...document.querySelectorAll('dialog')].at(-1)
    const originalSetItem = ui.dom.window.Storage.prototype.setItem
    let deniedKey = ORGANIZATION_KEY
    ui.dom.window.Storage.prototype.setItem = function (key, value) {
      if (key === deniedKey) throw new ui.dom.window.DOMException('Storage is full', 'QuotaExceededError')
      originalSetItem.call(this, key, value)
    }
    await click(byLabel('New folder'))
    await input(document.getElementById('folder-name'), 'Retry folder')
    await submit()
    assert.ok(document.getElementById('folder-name'))
    assert.equal(document.getElementById('folder-name').value, 'Retry folder')
    assert.match(dialog().textContent, /could not be saved/)
    assert.equal(JSON.parse(localStorage.getItem(ORGANIZATION_KEY)).folders.length, 1)
    deniedKey = null
    await submit()
    assert.equal(JSON.parse(localStorage.getItem(ORGANIZATION_KEY)).folders.length, 2)
    await click(byText('Preserved folder', document.querySelector('.folder-tree')))
    await click(byText('Delete', document.querySelector('.folder-tree')))
    deniedKey = NOTES_STORAGE_KEY
    await click(byText('Delete', dialog()))
    assert.match(dialog().textContent, /could not be saved/)
    assert.equal(JSON.parse(localStorage.getItem(ORGANIZATION_KEY)).folders.some(folder => folder.id === 'folder'), true)
    assert.equal(JSON.parse(localStorage.getItem(NOTES_STORAGE_KEY))[0].folderId, 'folder')
    deniedKey = null
    await click(byText('Delete', dialog()))
    assert.equal(JSON.parse(localStorage.getItem(NOTES_STORAGE_KEY))[0].folderId, null)
    await click(document.querySelector('.note-card'))
    await waitFor(() => editor())
    const tags = document.querySelector('.note-editor .tag-selector')
    await click(tags.querySelector('summary'))
    await click(byText('Manage tags', tags))
    await click(byLabel('Delete tag Preserved tag', dialog()))
    deniedKey = NOTES_STORAGE_KEY
    await click(byText('Delete', dialog()))
    assert.equal(JSON.parse(localStorage.getItem(ORGANIZATION_KEY)).tags.length, 1, 'tag remains until reference cleanup succeeds')
    assert.equal(JSON.parse(localStorage.getItem(NOTES_STORAGE_KEY))[0].tagIds.includes('tag'), true)
    deniedKey = null
    await click(byText('Delete', dialog()))
    assert.equal(JSON.parse(localStorage.getItem(ORGANIZATION_KEY)).tags.length, 0)
    assert.deepEqual(JSON.parse(localStorage.getItem(STORAGE_KEY))[0].tasks[0].tagIds, [])
    assert.deepEqual(JSON.parse(localStorage.getItem(NOTES_STORAGE_KEY))[0].tagIds, [])
    assert.equal(JSON.parse(localStorage.getItem(STORAGE_KEY))[0].tasks[0].id, project.tasks[0].id)
    assert.equal(JSON.parse(localStorage.getItem(NOTES_STORAGE_KEY))[0].id, note.id)
    assert.deepEqual(JSON.parse(localStorage.getItem(NOTES_STORAGE_KEY))[0].content, note.content)
    ui.dom.window.Storage.prototype.setItem = originalSetItem
  } finally { await ui.close() }
})
